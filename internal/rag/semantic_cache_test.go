const testVaultKey = "0123456789abcdef0123456789abcdef"

func newTestCache(t *testing.T, backend CacheBackend) *SemanticCacheManager {
	t.Helper()
	v, err := vault.NewNativeVaultManager(testVaultKey, store.NewMemory())
	if err != nil {
		t.Fatal(err)
	}
	c, err := NewSemanticCacheManager(backend, v, time.Hour, 2*time.Hour)
	if err != nil {
		t.Fatal(err)
	}
	return c
}

func answer(text string) *pod.PodResponse {
	return &pod.PodResponse{PodID: "POD_AFIP_FISCAL", Answer: text, Status: "SUCCESS", Model: "fake-model"}
}

func TestSPEC_CORE_71_R2_GlobalAnswerIsSharedAcrossTenants(t *testing.T) {
	ctx := context.Background()
	c := newTestCache(t, NewMemoryCacheBackend())

	c.StoreResponse(ctx, "tenant_a", "¿Cuándo vence SICORE?", answer("El día 10."), true)

	got, ok := c.GetCachedResponse(ctx, "tenant_b", "cuando vence sicore")
	if !ok {
		t.Fatal("tenant_b should reuse the GLOBAL answer generated by tenant_a")
	}
	if !got.Cached || got.CacheScope != CacheScopeGlobal || got.CacheStatus != CacheProvisional {
		t.Errorf("unexpected cache marks: cached=%t scope=%s status=%s", got.Cached, got.CacheScope, got.CacheStatus)
	}
}

func TestSPEC_CORE_71_R3_TenantAnswerIsIsolated(t *testing.T) {
	ctx := context.Background()
	c := newTestCache(t, NewMemoryCacheBackend())

	c.StoreResponse(ctx, "tenant_a", "saldo de mis facturas en Odoo", answer("Debés $ 1.000."), false)

	if _, ok := c.GetCachedResponse(ctx, "tenant_b", "saldo de mis facturas en Odoo"); ok {
		t.Fatal("SECURITY VIOLATION: tenant_b read tenant_a's private cached answer")
	}
	got, ok := c.GetCachedResponse(ctx, "tenant_a", "saldo de mis facturas en Odoo")
	if !ok || got.CacheScope != CacheScopeTenant {
		t.Fatalf("tenant_a should hit its own TENANT entry, got ok=%t", ok)
	}
}

func TestSPEC_CORE_71_R4_FeedbackLifecycle(t *testing.T) {
	ctx := context.Background()
	c := newTestCache(t, NewMemoryCacheBackend())
	q := "como genero el certificado de ARCA"
	c.StoreResponse(ctx, "tenant_a", q, answer("Con OpenSSL."), true)

	if !c.Promote(ctx, "tenant_b", q) {
		t.Fatal("👍 should promote the GLOBAL entry")
	}
	got, _ := c.GetCachedResponse(ctx, "tenant_a", q)
	if got == nil || got.CacheStatus != CacheVerified {
		t.Fatalf("expected VERIFIED after 👍, got %+v", got)
	}

	if !c.PurgeKey(ctx, "tenant_b", q) {
		t.Fatal("👎 should purge the entry")
	}
	if _, ok := c.GetCachedResponse(ctx, "tenant_a", q); ok {
		t.Fatal("after 👎 the next question must miss the cache")
	}
	if _, _, purged := c.Stats(); purged != 1 {
		t.Errorf("expected 1 purged entry, got %d", purged)
	}
}

func TestSPEC_CORE_71_R5_EntriesAreEncryptedAtRest(t *testing.T) {
	ctx := context.Background()
	backend := NewMemoryCacheBackend()
	c := newTestCache(t, backend)
	q := "alicuota de IVA para servicios"
	c.StoreResponse(ctx, "tenant_a", q, answer("Respuesta confidencial 21%"), false)

	raw, ok, err := backend.Get(ctx, cacheKey("tenant_a", q))
	if err != nil || !ok {
		t.Fatalf("entry not stored: ok=%t err=%v", ok, err)
	}
	if strings.Contains(string(raw), "confidencial") || strings.Contains(string(raw), "alicuota") {
		t.Fatal("cached entry is stored in clear text")
	}
	if strings.Contains(cacheKey("tenant_a", q), "alicuota") {
		t.Fatal("cache key leaks the query text")
	}
}

func TestSPEC_CORE_71_R5_TTLExpires(t *testing.T) {
	ctx := context.Background()
	backend := NewMemoryCacheBackend()
	now := time.Now()
	backend.now = func() time.Time { return now }
	c := newTestCache(t, backend)
	c.StoreResponse(ctx, "tenant_a", "q", answer("a"), false)

	now = now.Add(61 * time.Minute) // provisional TTL is 1h in newTestCache
	if _, ok := c.GetCachedResponse(ctx, "tenant_a", "q"); ok {
		t.Fatal("PROVISIONAL entry should expire after its TTL")
	}
}

// Integration test against a real Redis: REDIS_TEST_URL=localhost:6379 go test ./internal/rag/
func TestSPEC_CORE_71_R5_RedisPersistence(t *testing.T) {
	url := os.Getenv("REDIS_TEST_URL")
	if url == "" {
		t.Skip("REDIS_TEST_URL not set; skipping Redis integration test")
	}
	ctx := context.Background()
	backend, err := NewRedisCacheBackend(url)
	if err != nil {
		t.Fatal(err)
	}
	defer backend.Close()
	if err := backend.Ping(ctx); err != nil {
		t.Fatalf("redis not reachable: %v", err)
	}

	q := "test SPEC-CORE-71 " + time.Now().Format(time.RFC3339Nano)
	newTestCache(t, backend).StoreResponse(ctx, "tenant_a", q, answer("persistida"), true)

	// A second manager (a restarted process) reads the same entry.
	got, ok := newTestCache(t, backend).GetCachedResponse(ctx, "tenant_b", q)
	if !ok || got.Answer != "persistida" {
		t.Fatalf("expected the GLOBAL entry to survive a restart, got ok=%t", ok)
	}
	if !newTestCache(t, backend).PurgeKey(ctx, "tenant_a", q) {
		t.Fatal("purge on Redis failed")
	}
}

